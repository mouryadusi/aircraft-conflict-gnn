import os
import json
import pandas as pd
import numpy as np

from sklearn.metrics import (
    confusion_matrix,
    classification_report,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
)

BASE = "processed_data"
OUT = os.path.join(BASE, "final_evaluation_package")

os.makedirs(OUT, exist_ok=True)


# ============================================================
# LOAD FINAL PREDICTIONS
# ============================================================

GCN_PATH = os.path.join(
    BASE,
    "final_gcn_predictions.csv",
)

GAT_PATH = os.path.join(
    BASE,
    "final_gat_predictions.csv",
)

gcn = pd.read_csv(GCN_PATH)
gat = pd.read_csv(GAT_PATH)


# ============================================================
# EVALUATION FUNCTION
# ============================================================

def evaluate(df):

    y_true = df["label"].astype(int).to_numpy()
    y_prob = df["probability"].astype(float).to_numpy()
    y_pred = df["prediction"].astype(int).to_numpy()

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    )

    tn, fp, fn, tp = cm.ravel()

    results = {
        "samples": int(len(df)),
        "positive_labels": int(y_true.sum()),
        "negative_labels": int((y_true == 0).sum()),
        "positive_predictions": int(y_pred.sum()),
        "negative_predictions": int((y_pred == 0).sum()),

        "label_rate": float(y_true.mean()),
        "prediction_rate": float(y_pred.mean()),

        "precision": float(
            precision_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        ),

        "recall": float(
            recall_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        ),

        "f1": float(
            f1_score(
                y_true,
                y_pred,
                zero_division=0,
            )
        ),

        "roc_auc": float(
            roc_auc_score(
                y_true,
                y_prob,
            )
        ),

        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),

        "confusion_matrix": cm.tolist(),

        "classification_report": classification_report(
            y_true,
            y_pred,
            zero_division=0,
        ),
    }

    return results


gcn_results = evaluate(gcn)
gat_results = evaluate(gat)


# ============================================================
# FINAL RESULTS TABLE
# ============================================================

rows = [

    {
        "model": "GCN",
        "features": "Trajectory",
        **gcn_results,
    },

    {
        "model": "GAT",
        "features": "Trajectory + CPA",
        **gat_results,
    },

]

results_df = pd.DataFrame(rows)


# Keep a clean publication-style table

table = results_df[
    [
        "model",
        "features",
        "samples",
        "precision",
        "recall",
        "f1",
        "roc_auc",
    ]
].copy()


# ============================================================
# SAVE CSV
# ============================================================

csv_path = os.path.join(
    OUT,
    "FINAL_PREDICTION_LEVEL_RESULTS.csv",
)

table.to_csv(
    csv_path,
    index=False,
)


# ============================================================
# SAVE JSON
# ============================================================

json_path = os.path.join(
    OUT,
    "FINAL_PREDICTION_LEVEL_RESULTS.json",
)

with open(json_path, "w") as f:

    json.dump(
        {
            "evaluation_protocol":
                "Prediction-level evaluation on each model's respective final test population.",

            "comparison_warning":
                "GCN and GAT prediction files do not contain a common edge identifier and have different test-population sizes and class distributions. Therefore, results must not be interpreted as a same-edge paired comparison.",

            "GCN": gcn_results,
            "GAT": gat_results,
        },
        f,
        indent=4,
    )


